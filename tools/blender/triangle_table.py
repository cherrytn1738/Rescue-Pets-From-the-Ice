"""Writes TRIANGLE_COUNTS.md.

    python tools/blender/triangle_table.py store-assets/style-test/v3   (the v3 style test's counts json)
    python tools/blender/triangle_table.py --buildings                   (every building, upgrade set and pick,
        from the pipeline's manifests: store-assets/buildings/TRIANGLE_COUNTS.md)
"""
import glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
THEME_BUDGET = {"Scrappy": 6000, "Workshop": 10000, "Frost-tech": 15000, "Enchanted": 20000, "Legendary": 30000}
ORDER = ["IcePickPost", "HeatLamp", "ChiselMill", "IceDrill", "WreckingCrane", "FlamethrowerTurret", "LavaPump", "SunMirrorTower"]


def total(meshes):
    return sum(n for _, n in meshes)


def buildings():
    manifests = {}
    for path in glob.glob(os.path.join(ROOT, "store-assets", "buildings", "*", "*_manifest.json")):
        m = json.load(open(path, encoding="utf-8"))
        manifests[m["id"]] = m
    lines = ["# Buildings: triangle counts", "",
             "Generated by `tools/blender/triangle_table.py --buildings` from the pipeline's manifests. Budgets (whole building): "
             "Scrappy ~6,000, Workshop ~10,000, Frost-tech ~15,000, Enchanted ~20,000, Legendary ~30,000 including its five "
             "Masterwork upgrade sets. Each tier's own upgrade sets are listed beside it (shown on top of the station when bought). "
             "Every mesh stays under 10,000 triangles. FX stand-ins (particles in game) are not counted.", "",
             "## Per building and tier", "",
             "| Building | Tier | Form | Meshes | Station | Upgrade sets | Counted | Budget | vs budget | Largest mesh | Fits pad |",
             "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | :---: |"]
    over = []
    for bid in [b for b in ORDER if b in manifests]:
        m = manifests[bid]
        for tier in m["tiers"]:
            station = total(tier["meshes"])
            ups = sum(total(u["meshes"]) for u in tier["upgrades"])
            counted = station + (ups if tier["theme"] == "Legendary" else 0)
            budget = THEME_BUDGET[tier["theme"]]
            pct = (counted - budget) / budget * 100
            every = tier["meshes"] + [x for u in tier["upgrades"] for x in u["meshes"]]
            big = max(every, key=lambda x: x[1])
            if pct > 10:
                over.append("%s %s: %+.0f%%" % (m["name"], tier["theme"], pct))
            lines.append("| %s | %s | %s | %d | %s | %s | %s | %s | %+.0f%% | %s (%s) | %s |" % (
                m["name"], tier["theme"], tier["form"].split(":")[0], len(tier["meshes"]), f"{station:,}", f"{ups:,}", f"{counted:,}",
                f"{budget:,}", pct, big[0], f"{big[1]:,}", "yes" if tier["fitsPad"] else "**no**"))
    lines += ["", "More than 10% over budget: " + (", ".join(over) if over else "none."), ""]
    picks = os.path.join(ROOT, "store-assets", "tools", "IcePicks_manifest.json")
    if os.path.exists(picks):
        lines += ["## Ice picks", "", "| Pick | Triangles | Meshes |", "| --- | ---: | --- |"]
        for p in json.load(open(picks, encoding="utf-8"))["picks"]:
            lines.append("| %s | %s | %s |" % (p["name"], f"{total(p['meshes']):,}", ", ".join("%s %s" % (n, f"{c:,}") for n, c in p["meshes"])))
        lines.append("")
    lines += ["## Per mesh"]
    for bid in [b for b in ORDER if b in manifests]:
        m = manifests[bid]
        for tier in m["tiers"]:
            lines += ["", "### %s: %s" % (m["name"], tier["theme"]), "", "| Mesh | Triangles | Glow (Neon) |", "| --- | ---: | :---: |"]
            for mesh, tris in sorted(tier["meshes"], key=lambda x: -x[1]):
                lines.append("| %s | %s | %s |" % (mesh, f"{tris:,}", "yes" if mesh.endswith("Glow") else ""))
            for u in tier["upgrades"]:
                for mesh, tris in sorted(u["meshes"], key=lambda x: -x[1]):
                    lines.append("| %s (upgrade %d) | %s | %s |" % (mesh, u["upgrade"], f"{tris:,}", "yes" if mesh.endswith("Glow") else ""))
    out = os.path.join(ROOT, "store-assets", "buildings", "TRIANGLE_COUNTS.md")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines[6:6 + 2 + 5 * len(manifests)]))
    print("over 10%:", over)


BUDGETS = {"Scrappy": 6000, "Workshop": 10000, "Frost-tech": 15000, "Enchanted": 20000,
           "Legendary: Mecha Mole Titan": 30000, "Masterwork": 30000}
LABELS = {"Masterwork": "Legendary + all 5 Masterwork upgrades"}


def main(folder):
    table = json.load(open(os.path.join(folder, "triangle_counts.json"), encoding="utf-8"))
    lines = ["# Ice Drill v3: triangle counts", "",
             "Generated from `triangle_counts.json` (written by `tools/blender/ice_drill_tiers_v3.py`; this table by "
             "`tools/blender/triangle_table.py`). Every mesh stays under 10,000 triangles (safe for FBX import; Roblox allows 20,000).",
             "", "## Per tier", "", "| Tier | Meshes | Triangles | Budget | vs budget | Largest mesh |", "| --- | ---: | ---: | ---: | ---: | --- |"]
    for name, row in table.items():
        meshes = row["meshes"]
        total = sum(t for _, t in meshes)
        big = max(meshes, key=lambda m: m[1])
        budget = BUDGETS[name]
        lines.append(f"| {LABELS.get(name, name)} | {len(meshes)} | {total:,} | {budget:,} | {(total - budget) / budget * 100:+.0f}% | {big[0]} ({big[1]:,}) |")
    base = sum(t for _, t in table["Legendary: Mecha Mole Titan"]["meshes"])
    master = sum(t for _, t in table["Masterwork"]["meshes"])
    fx = table["Masterwork"].get("fx", [])
    lines += ["", f"Masterwork upgrade parts alone: {master - base:,} triangles. FX stand-ins (particles in game, not meshes): "
              f"{sum(t for _, t in fx):,} triangles in {len(fx)} preview meshes, not counted above.", "", "## Per mesh"]
    for name, row in table.items():
        lines += ["", f"### {name}", "", "| Mesh | Triangles | Glow (Neon) |", "| --- | ---: | :---: |"]
        for mesh, tris in sorted(row["meshes"], key=lambda m: -m[1]):
            lines.append(f"| {mesh} | {tris:,} | {'yes' if mesh.endswith('Glow') else ''} |")
    open(os.path.join(folder, "TRIANGLE_COUNTS.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines[6:14]))


if __name__ == "__main__":
    if sys.argv[1] == "--buildings":
        buildings()
    else:
        main(sys.argv[1])
