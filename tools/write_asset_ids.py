"""write_asset_ids.py - copies the uploaded asset ids from the upload manifests into the configs and
ASSET_IDS.md. Run it after tools/upload_models.py; re-running it is safe.

    python tools/write_asset_ids.py

Reads:   store-assets/buildings/upload_manifest.json  (stations and upgrade part sets, Models)
         store-assets/tools/upload_manifest.json      (ice picks, Models)
         assets/textures/upload_manifest.json         (the building palette, particle and ice textures, Images)
         store-assets/ice-block/upload_manifest.json  (the ice block's look options, Models)
Writes the generated block (between "-- BEGIN ASSET IDS" and "-- END ASSET IDS") in
         src/replicated/BuildingConfig.luau   BuildingConfig.PaletteTextureId, BuildingConfig.ModelIds
         src/replicated/UpgradeConfig.luau    UpgradeConfig.PickModelIds
         src/replicated/EffectsConfig.luau    EffectsConfig.Textures
         src/replicated/IceLooks.luau         IceLooks.Textures, IceLooks.OptionModelIds
and ASSET_IDS.md (every asset, its file and its moderation state).
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["IcePickPost", "HeatLamp", "ChiselMill", "IceDrill", "WreckingCrane", "FlamethrowerTurret", "LavaPump", "SunMirrorTower"]
PICKS = ["Wooden", "Stone", "Iron", "Gold", "Diamond", "Cosmic"]
TEXTURE_KEYS = {"soft_glow.png": "SoftGlow", "sparkle.png": "Sparkle", "snowflake.png": "Snowflake", "ember.png": "Ember",
                "smoke_puff.png": "SmokePuff", "star.png": "Star", "water_droplet.png": "WaterDroplet",
                "rune_1.png": "Rune1", "rune_2.png": "Rune2", "rune_3.png": "Rune3", "rune_4.png": "Rune4"}
ICE_TEXTURES = {"IceBlueAtlas.png": "Atlas", "IceGlow.png": "Glow", "IceShimmer.png": "Shimmer"}
ICE_OPTIONS = ["A", "B", "C"]


def manifest(path):
    full = os.path.join(ROOT, path)
    if not os.path.exists(full):
        return {}
    data = json.load(open(full, encoding="utf-8"))
    return data.get("assets", data)


def replace_block(path, block):
    full = os.path.join(ROOT, path)
    text = open(full, encoding="utf-8").read()
    pattern = re.compile(r"-- BEGIN ASSET IDS.*?-- END ASSET IDS\n", re.S)
    if not pattern.search(text):
        sys.exit("no generated block in " + path)
    text = pattern.sub(lambda _: block, text)
    open(full, "w", encoding="utf-8", newline="\n").write(text)


def main():
    buildings = manifest("store-assets/buildings/upload_manifest.json")
    picks = manifest("store-assets/tools/upload_manifest.json")
    textures = manifest("assets/textures/upload_manifest.json")
    rows = []  # (kind, name, file, id, state)

    def asset(m, key):
        e = m.get(key) or {}
        return e.get("assetId"), e.get("moderationState") or ("pending" if e.get("operation") else "not uploaded")

    lines = ["-- BEGIN ASSET IDS (generated by tools/write_asset_ids.py from the upload manifests; don't edit by hand)\n"]
    pid, state = asset(textures, "BuildingPalette.png")
    rows.append(("Image", "Building palette texture", "assets/textures/BuildingPalette.png", pid, state))
    lines.append('BuildingConfig.PaletteTextureId = %s\n' % ('"rbxassetid://%s"' % pid if pid else "nil"))
    lines.append("BuildingConfig.ModelIds = { -- per building: the station for each tier, and that tier's upgrade part sets\n")
    for bid in ORDER:
        st, up = [], []
        for t in range(1, 6):
            for kind, key, out in (("station", "%s/fbx/%s_T%d.fbx" % (bid, bid, t), st), ("upgrades", "%s/fbx/%s_T%d_Upgrades.fbx" % (bid, bid, t), up)):
                aid, state = asset(buildings, key)
                out.append(aid or "nil")
                rows.append(("Model", "%s tier %d %s" % (bid, t, kind), "store-assets/buildings/" + key, aid, state))
        lines.append("\t%s = { Stations = { %s }, Upgrades = { %s } },\n" % (bid, ", ".join(st), ", ".join(up)))
    lines.append("}\n-- END ASSET IDS\n")
    replace_block("src/replicated/BuildingConfig.luau", "".join(lines))

    ids = []
    for t in range(1, 7):
        aid, state = asset(picks, "fbx/IcePick_T%d.fbx" % t)
        ids.append(aid or "nil")
        rows.append(("Model", "Ice pick tier %d (%s)" % (t, PICKS[t - 1]), "store-assets/tools/fbx/IcePick_T%d.fbx" % t, aid, state))
    replace_block("src/replicated/UpgradeConfig.luau",
                  "-- BEGIN ASSET IDS (generated by tools/write_asset_ids.py from the upload manifests; don't edit by hand)\n"
                  "UpgradeConfig.PickModelIds = { %s } -- by tier\n-- END ASSET IDS\n" % ", ".join(ids))

    tex = ["-- BEGIN ASSET IDS (generated by tools/write_asset_ids.py from the upload manifests; don't edit by hand)\n",
           "EffectsConfig.Textures = {\n"]
    for file, key in TEXTURE_KEYS.items():
        aid, state = asset(textures, "particles/" + file)
        tex.append('\t%s = %s,\n' % (key, '"rbxassetid://%s"' % aid if aid else "nil"))
        rows.append(("Image", "Particle texture " + key, "assets/textures/particles/" + file, aid, state))
    tex.append("}\n-- END ASSET IDS\n")
    replace_block("src/replicated/EffectsConfig.luau", "".join(tex))

    ice = manifest("store-assets/ice-block/upload_manifest.json")
    block = ["-- BEGIN ASSET IDS (generated by tools/write_asset_ids.py from the upload manifests; don't edit by hand)\n",
             "IceLooks.Textures = {\n"]
    for file, key in ICE_TEXTURES.items():
        aid, state = asset(textures, "ice/" + file)
        block.append('\t%s = %s,\n' % (key, '"rbxassetid://%s"' % aid if aid else "nil"))
        rows.append(("Image", "Ice block texture " + key, "assets/textures/ice/" + file, aid, state))
    block.append("}\nIceLooks.OptionModelIds = {\n")
    for option in ICE_OPTIONS:
        aid, state = asset(ice, "IceBlock%s.fbx" % option)
        block.append("\t%s = %s,\n" % (option, aid or "nil"))
        rows.append(("Model", "Ice block option " + option, "store-assets/ice-block/IceBlock%s.fbx" % option, aid, state))
    block.append("}\n-- END ASSET IDS\n")
    replace_block("src/replicated/IceLooks.luau", "".join(block))

    md = ["# Asset ids", "",
          "Every uploaded asset of the game, created by the group 921449746 with `tools/upload_models.py`. Generated by",
          "`python tools/write_asset_ids.py` from the upload manifests, which also writes the ids into `BuildingConfig`,",
          "`UpgradeConfig`, `EffectsConfig` and `IceLooks`. Don't edit by hand.", "",
          "| Type | What | File | Asset id | Moderation |", "| --- | --- | --- | --- | --- |"]
    for kind, name, file, aid, state in rows:
        md.append("| %s | %s | `%s` | %s | %s |" % (kind, name, file, aid or "-", state))
    held = [r for r in rows if r[4] != "Approved"]
    md += ["", "Not approved yet: " + (", ".join("%s (%s)" % (r[1], r[4]) for r in held) if held else "none."), ""]
    open(os.path.join(ROOT, "ASSET_IDS.md"), "w", encoding="utf-8", newline="\n").write("\n".join(md))
    print("%d assets, %d not approved" % (len(rows), len(held)))
    for r in held:
        print("  NOT APPROVED:", r[1], r[4])


if __name__ == "__main__":
    main()
